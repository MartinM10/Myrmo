// Keeps the list of every documentation page in web/llms.txt (the index that agents read) in step with the pages.
//
//   node scripts/llms.mjs --check    fails when the list is out of date (CI)
//   node scripts/llms.mjs --write    rewrites it from the title and description of each page
//
// The list sits between two markers; everything else in llms.txt is written by hand.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { pages } from "./pages.mjs";

const docs = join(dirname(fileURLToPath(import.meta.url)), "..");
const llms = join(docs, "..", "web", "llms.txt");
const START = "<!-- pages:start (generated by docs/scripts/llms.mjs; do not edit) -->";
const END = "<!-- pages:end -->";
const GROUPS = [
  ["getting-started", "Getting started"],
  ["concepts", "Concepts"],
  ["reference", "Reference"],
  ["operate", "Operate"],
  ["security", "Security"],
  ["legal", "Legal"],
];

function front(file) {
  const text = readFileSync(join(docs, file), "utf8");
  const block = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? "";
  const field = (name) => {
    const m = new RegExp(`^${name}:\\s*(.*)$`, "m").exec(block)?.[1]?.trim() ?? "";
    return m.replace(/^"(.*)"$/, "$1");
  };
  return { title: field("title"), description: field("description") };
}

function section() {
  const lines = [START, ""];
  const all = pages();
  for (const [folder, label] of GROUPS) {
    const inGroup = all.filter((f) => f.startsWith(`${folder}/`));
    if (!inGroup.length) continue;
    lines.push(`### ${label}`, "");
    for (const file of inGroup) {
      const { title, description } = front(file);
      const url = `https://myrmo.dev/docs/${file.replace(/\.md$/, "")}`;
      lines.push(`- [${title}](${url}): ${description}`);
    }
    lines.push("");
  }
  lines.push("Every page is also served as markdown: add `.md` to its address. All of them in one file: https://myrmo.dev/docs/llms-full.txt", "", END);
  return lines.join("\n");
}

const current = readFileSync(llms, "utf8");
const a = current.indexOf(START);
const b = current.indexOf(END);
if (a < 0 || b < 0) {
  console.error(`web/llms.txt has no "${START}" ... "${END}" markers.`);
  process.exit(2);
}
const next = current.slice(0, a) + section() + current.slice(b + END.length);
if (process.argv.includes("--write")) {
  writeFileSync(llms, next);
  console.log("web/llms.txt updated");
} else if (next !== current) {
  console.error("web/llms.txt does not list the documentation pages as they are. Run: node scripts/llms.mjs --write");
  process.exit(1);
} else {
  console.log("web/llms.txt lists every page");
}
