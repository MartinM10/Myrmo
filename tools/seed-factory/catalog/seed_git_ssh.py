# sshd on 127.0.0.1:2222 that accepts the root key of this container (no host key trust yet).


def sshd(name: str = "id_ed25519") -> str:
    """sshd on 127.0.0.1:2222 that accepts only the key /root/.ssh/<name> (a fresh key the setup creates)."""
    return (
        f"mkdir -p /run/sshd /root/.ssh && chmod 700 /root/.ssh && ssh-keygen -q -t ed25519 -N '' -f /root/.ssh/{name}"
        f" && cat /root/.ssh/{name}.pub >> /root/.ssh/authorized_keys && chmod 600 /root/.ssh/authorized_keys && /usr/sbin/sshd -p 2222"
    )


